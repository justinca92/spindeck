/** 95 min → "1.6", 754 min → "12.6", 6000 min → "100". */
const fmtHours = (min: number) => {
  const h = min / 60;
  return h >= 100 ? String(Math.round(h)) : (Math.round(h * 10) / 10).toString();
};

